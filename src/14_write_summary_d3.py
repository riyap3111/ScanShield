"""Step 14: Build RESULTS_DELIVERABLE3.md from the saved outputs only.

Every number in the Status Report also appears here, read straight out of outputs/tables and
outputs/metrics, so nothing in the write-up is typed by hand twice.
"""
import json
import datetime as dt
import subprocess

import pandas as pd

from config import ROOT, TAB_DIR, MET_DIR, TARGET_RECALL, TARGET_FPR

OUT = ROOT / "RESULTS_DELIVERABLE3.md"


def t(name):
    p = TAB_DIR / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


def j(name):
    p = MET_DIR / f"{name}.json"
    return json.load(open(p)) if p.exists() else None


def md(df, cols=None, **kw):
    if df is None:
        return "_(not generated: run the matching pipeline step)_"
    d = df[cols] if cols else df
    return d.to_markdown(index=False, floatfmt=".5g", **kw)


def pct(x, d=3):
    return "n/a" if pd.isna(x) else f"{x * 100:.{d}f}%"


def main():
    comp = t("model_comparison")
    tune = t("model_tuning")
    cvv = t("cv_variance")
    thr = t("threshold_choice")
    cost = t("compute_cost")
    abl = t("feature_set_ablation")
    seed = t("seed_stability")
    eng = t("engineered_features")
    causes = t("error_causes")
    eprof = t("error_analysis_v2")
    gen_day = t("generalization_by_day")
    gen_att = t("generalization_by_attack")
    gen_sum = t("generalization_summary")
    schema = t("schema_compatibility")
    adv = t("adversarial_results")
    advd = t("adversarial_defense")
    svc = t("subgroup_service")
    sub = t("subgroup_summary")
    imp = t("explainability_importance")
    psi = t("drift_psi")
    vol = t("alert_volume")
    plan = t("monitoring_plan")
    flow = t("response_workflow")
    runtime = j("runtime") or {}

    test = comp[comp.split == "test (locked)"].copy() if comp is not None else None
    best_row = test.sort_values(["f1", "pr_auc"], ascending=False).iloc[0] if test is not None else None
    best = best_row.model if best_row is not None else "n/a"

    try:
        commit = subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                                         stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        commit = "n/a"

    L = []
    w = L.append
    w("# ScanShield — Deliverable 3 results\n")
    w(f"_Generated by `src/14_write_summary_d3.py` on "
      f"{dt.date.today().isoformat()} from commit `{commit}`. Every number is read from "
      f"`outputs/tables/` and `outputs/metrics/`._\n")
    w(f"**Selected model: {best}.** Success criteria from the proposal: recall on scans "
      f"≥ {TARGET_RECALL:.2f}, false-positive rate on benign traffic ≤ {TARGET_FPR:.0%}.\n")

    if best_row is not None:
        w("| Metric on the locked test split | Value |")
        w("|---|---|")
        for k, label in [("precision", "Precision"), ("recall", "Recall"), ("f1", "F1"),
                         ("fpr", "False-positive rate"), ("fnr", "False-negative rate"),
                         ("pr_auc", "PR-AUC"), ("roc_auc", "ROC-AUC")]:
            v = best_row[k]
            w(f"| {label} | {pct(v) if k in ('fpr', 'fnr') else f'{v:.5f}'} |")
        w(f"| Confusion matrix | TN {int(best_row.TN):,} · FP {int(best_row.FP):,} · "
          f"FN {int(best_row.FN):,} · TP {int(best_row.TP):,} |")
        w("")

    w("## 1. Feature engineering\n")
    w("Every original CICFlowMeter column is kept; the engineered features are additions, not "
      "replacements.\n")
    if eng is not None:
        w(md(eng, ["feature", "definition", "median_scan", "median_benign"]))
    w("")

    w("## 2. Model development and tuning\n")
    if tune is not None:
        w(md(tune, ["model", "best_cv_pr_auc", "best_params", "search_seconds"]))
        w("")
        for _, r in tune.iterrows():
            w(f"- **{r.model}** — {r.rationale}")
        w("")
    w("### 5-fold cross-validation on the training split (mean ± sd)\n")
    if cvv is not None:
        w(md(cvv))
    w("")
    if seed is not None:
        w("### Seed stability of the selected family (validation)\n")
        w(md(seed))
        w("")

    w("## 3. Evaluation\n")
    if comp is not None:
        w(md(comp, ["model", "split", "precision", "recall", "f1", "fpr", "fnr",
                    "pr_auc", "roc_auc", "TN", "FP", "FN", "TP"]))
        w("")
    if thr is not None:
        w("### Operating threshold (chosen on validation, frozen before the test split was read)\n")
        w(md(thr))
        w("")
    if abl is not None:
        w("### Feature-set ablation\n")
        w(md(abl, ["feature_set", "n_features", "recall", "fpr", "pr_auc", "monday_fpr"]))
        w("")
    if cost is not None:
        w("### Compute cost and throughput\n")
        w(md(cost, ["model", "fit_seconds_149k_rows", "score_seconds_32k_rows",
                    "flows_scored_per_second", "model_size_mb"]))
        w("")

    w("## 4. Error analysis\n")
    if causes is not None:
        w(md(causes))
        w("")
    if eprof is not None:
        w("### Median feature values by outcome\n")
        w(md(eprof))
        w("")

    w("## 5. Generalization testing\n")
    if gen_sum is not None:
        w(md(gen_sum))
        w("")
    if gen_day is not None:
        w("### Per unseen capture day\n")
        w(md(gen_day, ["day", "description", "rows_after_cleaning", "benign_flows",
                       "benign_flagged", "benign_fpr", "within_5pct_ceiling"]))
        w("")
    if gen_att is not None:
        w("### Attack types never seen in training\n")
        w(md(gen_att))
        w("")
    if schema is not None:
        w("### Schema compatibility\n")
        w(md(schema, ["day", "n_columns", "encoding_needed",
                      "columns_identical_to_training_file", "missing_columns", "extra_columns"]))
        w("")

    w("## 6. Adversarial threat model\n")
    if adv is not None:
        w(md(adv, ["attack", "realisation", "recall_under_attack", "evasion_rate"]))
        w("")
    if advd is not None:
        w("### Defense: adversarial training\n")
        w(md(advd))
        w("")

    w("## 7. Responsible AI\n")
    if sub is not None:
        w("### Performance spread across groups\n")
        w(md(sub))
        w("")
    if svc is not None:
        w("### By service group\n")
        w(md(svc, ["service_group", "flows", "scan_flows", "benign_flows", "recall", "fpr"]))
        w("")
    if imp is not None:
        w("### Top features (permutation importance)\n")
        w(md(imp.head(15)))
        w("")

    w("## 8. Monitoring\n")
    if vol is not None:
        w("### Alert-volume baseline on unseen days\n")
        w(md(vol, ["day", "flows_scored", "alerts", "alerts_per_10k_flows",
                   "median_alert_score", "max_feature_psi"]))
        w("")
    if psi is not None:
        w("### Most-drifted features\n")
        w(md(psi.head(12)))
        w("")
    if plan is not None:
        w("### Monitoring plan\n")
        w(md(plan))
        w("")
    if flow is not None:
        w("### Response workflow\n")
        w(md(flow))
        w("")

    w("## Reproducibility\n")
    w(f"- `bash run_all.sh` rebuilds everything above from the raw CSVs"
      + (f" (last full run: {runtime.get('total_seconds', '?')} s)." if runtime else "."))
    w("- `random_state = 42` everywhere; the tuned configurations are recorded in "
      "`outputs/tables/model_tuning.csv`.")
    w("- The test split was scored once, after the threshold was frozen on validation.")
    w("")

    OUT.write_text("\n".join(L))
    print(f"wrote {OUT} ({len(''.join(L)):,} characters)")


if __name__ == "__main__":
    main()
